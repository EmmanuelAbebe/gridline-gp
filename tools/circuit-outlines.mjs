// The start menu's circuit outlines (src/game/circuit-outlines.js): each circuit's centre line as an SVG path in a
// 200 × 120 box, its start line, length, corners and whether it has hills, so the menu draws every circuit without
// building them (a track takes ~0.1–0.5 s). `npm run outlines` after a circuit changes (tests/menu.test.js checks it).
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SIM } from '../src/sim/index.js';

export function outlinesSource() {
  const out = {};
  for (const [id, c] of Object.entries(SIM.CIRCUITS)) {
    const T = SIM.buildTrack(c), step = Math.max(1, Math.round(T.N / 160));
    let x0 = Infinity, x1 = -Infinity, z0 = Infinity, z1 = -Infinity;
    for (let i = 0; i < T.N; i++) { x0 = Math.min(x0, T.PX[i]); x1 = Math.max(x1, T.PX[i]); z0 = Math.min(z0, T.PZ[i]); z1 = Math.max(z1, T.PZ[i]); }
    const s = Math.min(184 / (x1 - x0), 104 / (z1 - z0)), ox = (200 - (x1 - x0) * s) / 2, oz = (120 - (z1 - z0) * s) / 2;
    const P = i => [+(ox + (T.PX[i] - x0) * s).toFixed(1), +(oz + (T.PZ[i] - z0) * s).toFixed(1)];
    let d = '';
    for (let i = 0; i < T.N; i += step) { const [a, b] = P(i); d += (i ? 'L' : 'M') + a + ' ' + b; }
    out[id] = { d: d + 'Z', start: P(0), km: +(T.N * T.ds / 1000).toFixed(2), corners: SIM.buildSectors(T).corners.length, hills: !!T.elev };
  }
  return `// Generated by tools/circuit-outlines.mjs (npm run outlines): every circuit's outline for the start menu.\nexport const OUTLINES = ${JSON.stringify(out)};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(new URL('../src/game/circuit-outlines.js', import.meta.url), outlinesSource());
  console.log('src/game/circuit-outlines.js');
}
