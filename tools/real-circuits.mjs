// node tools/real-circuits.mjs <prep dir>: writes src/sim/circuits-real.js from the prepared outlines (prep-<id>.json:
// { ctrl, heights }; made from bacinger/f1-circuits (MIT) and OpenStreetMap (ODbL) outlines + OpenTopoData heights, see
// CREDITS.md). The data only: names, widths, themes and landmarks are in circuits.js.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = process.argv[2], ids = ['monza', 'monaco', 'mexicofe'];
// flat: the real site is (Mexico City's Formula E layout varies ~2 m; its SRTM heights read the stadium's stands as 16 m hills)
const FLAT = new Set(['mexicofe']);
const row = a => '[' + a.map(v => v === null ? 'null' : v).join(',') + ']';
let s = '// Real circuits\' outlines and heights (generated by tools/real-circuits.mjs; do not edit by hand). Sources: CREDITS.md.\n' +
  '// ctrl: [x, z] every ~18 m from the start line (x east, z south, metres); heights: [x, z, height m | null, bank] every ~30 m;\n' +
  '// tunnels: [from, to] metres along the lap (world.js builds them).\n' +
  'export const REAL_OUTLINES = Object.freeze({\n';
for (const id of ids) {
  const { ctrl, heights, tunnels } = JSON.parse(readFileSync(`${dir}/prep-${id}.json`));
  s += `  ${id}: {\n    ctrl: [${ctrl.map(row).join(',')}],\n${FLAT.has(id) ? '' : `    heights: [${heights.map(row).join(',')}],\n`}${tunnels?.length ? `    tunnels: ${JSON.stringify(tunnels)},\n` : ''}  },\n`;
}
writeFileSync(new URL('../src/sim/circuits-real.js', import.meta.url), s + '});\n');
console.log('wrote src/sim/circuits-real.js', ids.join(', '));
